class RuleMapper:
    """Сопоставляет события с нормативными источниками РК."""

    def rule(self, event_type: str) -> dict | None:
        """Структурированная норма для типа события или None, если нормы нет."""
        r = RULES.get(event_type)
        if r is None:
            return None
        return {k: r[k] for k in ("document", "clause", "quote", "note", "url")}

    def map(self, event_type: str) -> dict:
        r = RULES.get(event_type)
        if r is None:
            return {"document": None, "clause": None, "url": None, "quote": None, "note": None,
                    "verified": False, "limitation": "Нормативный источник не найден."}
        return {**r, "verified": True}

    def format_reference(self, event_type: str) -> str | None:
        """Короткая строка со ссылкой (для обратной совместимости и отчётов)."""
        r = RULES.get(event_type)
        if r is None:
            return None
        return f"{r['document']}, {r['clause']} | Источник: {r['url']}"

    def format_limitations(self, event_type: str) -> str | None:
        r = RULES.get(event_type)
        return r["limitation"] if r else None
